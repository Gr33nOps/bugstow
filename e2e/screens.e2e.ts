import { expect, test } from '@playwright/test'

test('Project and settings dialogs contain keyboard focus and close with Escape', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start with Local' }).click()
  await page.getByRole('button', { name: /^Projects/ }).first().click()
  await page.getByRole('button', { name: /New project/ }).first().click()
  const project = page.getByRole('dialog', { name: 'New project' })
  await expect(project).toBeVisible()
  await project.getByRole('button', { name: 'Cancel' }).focus()
  await page.keyboard.press('Tab')
  await expect.poll(() => project.evaluate(el => el.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(project).not.toBeVisible()
  await page.getByRole('button', { name: /^Settings/ }).first().click()
  await page.getByRole('button', { name: 'Data & backups' }).click()
  await page.getByRole('button', { name: /^Download backup/ }).click()
  const backup = page.getByRole('dialog', { name: 'Download backup' })
  await expect(backup).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(backup).not.toBeVisible()
})

